# shellcheck shell=dash
# Запись authorized_keys.
#
# Функция не парсер и не чистая — она пишет файл. В `lib/` она живёт по другой
# причине: только отсюда её можно проверить тестом. `wrt.cloudinit` — init-скрипт
# `rc.common`, в тест-харнесс его не подтянуть, а без теста «ключи больше не
# удваиваются» остаётся обещанием.

# merge_authorized_keys <файл> <ключи> → положить ключи ровно по одному разу,
# не потеряв чужих строк. Пустой список ключей — ничего не делаем.
#
# Раньше `install_ssh_keys` дописывал ключи (`>> authorized_keys`), и при
# повторном провижне (новый `instance-id`) строки удваивались. Работать это
# продолжало, поэтому росло молча.
#
# Почему не простое затирание (`>`), хотя задача звучит как «записывать, а не
# дописывать»: за один провижн в один и тот же файл пишут несколько раз.
# `install_ssh_keys` зовётся на КАЖДОГО пользователя из списка `users:`,
# а `/etc/dropbear/authorized_keys` у всех общий — затирание оставило бы в нём
# ключи только последнего пользователя. Плюс в образе там может лежать ключ,
# положенный сборкой, и он тоже не наш. То есть `>` обменял бы удвоение
# на потерю ключей, а это дороже.
#
# Чего функция НЕ делает: ключ, убранный из сида, с устройства не исчезает —
# снять его остаётся отдельным действием. И уже надублированные строки на
# прошитых устройствах она не чинит: правка живёт внутри образа и доезжает
# только новой записью носителя.
merge_authorized_keys() {
	local file=$1 keys=$2 tmp
	[ -n "$keys" ] || return 0
	tmp="$file.wrt-new"

	if [ -f "$file" ]; then
		# Выкидываем ровно те строки, которые сейчас запишем сами, —
		# остальное содержимое файла сохраняется как есть.
		awk -v keys="$keys" '
			BEGIN { n = split(keys, k, "\n"); for (i = 1; i <= n; i++) mine[k[i]] = 1 }
			!($0 in mine)
		' "$file" > "$tmp" || return 1
	else
		: > "$tmp" || return 1
	fi
	printf '%s\n' "$keys" >> "$tmp" || return 1

	# `cat > файл`, а не `mv`: так сохраняются права и владелец уже
	# существующего authorized_keys. Тот же приём стоит в update_shadow_entry.
	cat "$tmp" > "$file" && rm -f "$tmp"
}
